"""Kinect v2 (Xbox One) через libfreenect2 — базовый датчик объекта. Заготовка.

Что за датчик: кадр глубины 512×424 точки, поле зрения 70°×60°, рабочая
дистанция 0,5–4,5 м, подключение USB 3.0 плюс свой блок питания (адаптер
Kinect Adapter для ПК). Меряет расстояние временем полёта света, а не
ИК-сеткой, поэтому не теряет крутые склоны и борта ящика.

Геометрия объекта: ось датчика 1,30 м над песком (1,45 м от пола), зона охвата
на этой высоте 1,82×1,50 м, 3,6 мм на точку (ящик 1,2 м — 337 точек поперёк),
шум по высоте ≈ 2 мм. Зона охвата больше картинки проектора (1,24×0,95 м),
поэтому размер ящика датчик не ограничивает. Стена попадает в кадр ниже 0,86 м
от пола (глубина ящика 600, центр X = 338 мм) — эту часть кадра обрезаем.

Задержка самого датчика ≈ 60–70 мс при общем бюджете отклика 130–190 мс.
USB: контроллер USB 3.0 должен быть Intel или Renesas — на контроллерах AMD и
через дешёвые хабы датчик часто не заводится; включать в порт материнской
платы напрямую, без хаба.

Дешёвая альтернатива — Kinect v1 (kinect1.py): точка мельче (2,0 мм против
3,6), но высота шумнее (≈3 мм против 2) и на крутых склонах и бортах ИК-сетка
теряет данные. Для песка обмен в пользу v2: детали рельефа крупнее 3,6 мм.
Консоль одна на оба датчика, меняется только высота подвеса.

Драйверы: libfreenect2 (Linux), обёртка Python — пакет pylibfreenect2; на
Windows (этап 0) — Kinect SDK 2.0. Доступ к USB без root даёт правило udev
deploy/kiosk/99-sandbox-sensors.rules.

Реализовать на этапе 1: открытие устройства, поток глубины 512×424 в мм 30 к/с,
цветной кадр 1920×1080 по желанию, перезапуск при потере кадров, подсчёт к/с и
ошибок для health().
"""
